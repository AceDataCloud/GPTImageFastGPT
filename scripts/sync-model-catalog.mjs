import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs, isDeepStrictEqual } from 'node:util';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OPERATIONS = {
  generation: { apiId: '8f01fe72-8a3e-4872-8d8d-330cde179b3a', path: '/openai/images/generations' },
  edit: { apiId: 'fb74083e-bb68-48d5-8ba6-b5a224400cd3', path: '/openai/images/edits' }
};

function resolveRef(value, spec) {
  const seen = new Set();
  while (value?.$ref) {
    const ref = value.$ref;
    if (!ref.startsWith('#/') || seen.has(ref)) throw new Error('Only non-recursive local schema references are supported.');
    seen.add(ref);
    value = spec;
    for (const part of ref.slice(2).split('/')) value = value[part.replaceAll('~1', '/').replaceAll('~0', '~')];
  }
  return value;
}

function enumValues(property, spec) {
  const values = resolveRef(property, spec)?.enum;
  if (!Array.isArray(values) || values.length === 0 || values.some(value => typeof value !== 'string') || new Set(values).size !== values.length) {
    throw new Error('A nonempty unique string enum is required. Existing catalog was not changed.');
  }
  return values;
}

export function projectOperation(spec, path) {
  const body = resolveRef(spec.paths?.[path]?.post?.requestBody, spec);
  const schema = resolveRef(body?.content?.['application/json']?.schema, spec);
  if (!schema?.properties) throw new Error(`Missing request schema for ${path}`);
  const supported = new Set(['prompt', 'model', 'image', 'size', 'quality', 'n', 'async', 'response_format']);
  if ((schema.required ?? []).some(name => !supported.has(name))) throw new Error('Required API fields changed; review the plugin before updating models.');
  return { models: enumValues(schema.properties.model, spec), qualities: enumValues(schema.properties.quality, spec) };
}

export function renderCatalog(snapshot) {
  if (!snapshot?.operations || Object.keys(snapshot.operations).join(',') !== Object.keys(OPERATIONS).join(',')) {
    throw new Error('Both image operations are required in the catalog.');
  }
  const lines = ['// Generated by scripts/sync-model-catalog.mjs. Do not edit.', ''];
  for (const [name, value] of Object.entries(snapshot.operations)) {
    for (const [field, values] of Object.entries(value)) {
      if (!['models', 'qualities'].includes(field)) continue;
      enumValues({ enum: values }, {});
      lines.push(`export const ${name.toUpperCase()}_${field.toUpperCase()} = ${JSON.stringify(values, null, 2)} as const;`, '');
    }
  }
  return lines.join('\n');
}

export async function fromBundle(bundleDir) {
  const manifest = JSON.parse(await readFile(resolve(bundleDir, 'manifest.json'), 'utf8'));
  const raw = await readFile(resolve(bundleDir, 'openapi/openai.json'));
  if (manifest.producer !== 'AceDataCloud/PlatformBackend' || manifest.files['openapi/openai.json'] !== `sha256:${createHash('sha256').update(raw).digest('hex')}`) {
    throw new Error('The OpenAI contract does not match its PlatformBackend bundle.');
  }
  const spec = JSON.parse(raw);
  return { source: { kind: 'PlatformBackend bundle', revision: manifest.source_sha }, operations: Object.fromEntries(Object.entries(OPERATIONS).map(([name, operation]) => [name, projectOperation(spec, operation.path)])) };
}

export async function fromPublicApi(fetcher = fetch) {
  const entries = await Promise.all(Object.entries(OPERATIONS).map(async ([name, operation]) => {
    const response = await fetcher(`https://platform.acedata.cloud/api/v1/apis/${operation.apiId}/`, { signal: AbortSignal.timeout(30000) });
    if (!response.ok) throw new Error(`Public contract request failed: HTTP ${response.status}`);
    const api = await response.json();
    return [name, projectOperation(api.definition, operation.path)];
  }));
  return { source: { kind: 'published API contracts', apiIds: Object.values(OPERATIONS).map(value => value.apiId) }, operations: Object.fromEntries(entries) };
}

async function main() {
  const { values } = parseArgs({ options: { check: { type: 'boolean' }, refresh: { type: 'boolean' }, 'bundle-dir': { type: 'string' } } });
  if (values.refresh && values['bundle-dir']) throw new Error('Choose a public refresh or a verified bundle.');
  const snapshotPath = resolve(root, 'contracts/image-models.json');
  const outputPath = resolve(root, 'src/model-catalog.ts');
  const current = await readFile(snapshotPath, 'utf8').then(JSON.parse).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  const incoming = values['bundle-dir'] ? await fromBundle(values['bundle-dir']) : values.refresh ? await fromPublicApi() : current;
  if (!incoming) throw new Error('Provide a verified bundle or refresh the published contracts.');
  const snapshot = current && isDeepStrictEqual(current.operations, incoming.operations) ? current : incoming;
  const source = renderCatalog(snapshot);
  if (values.check) {
    if (await readFile(outputPath, 'utf8') !== source) throw new Error('Generated model catalog is stale.');
  } else {
    await writeFile(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`);
    await writeFile(outputPath, source);
  }
  console.log(JSON.stringify(Object.fromEntries(Object.entries(snapshot.operations).map(([name, operation]) => [name, operation.models.length]))));
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main();
